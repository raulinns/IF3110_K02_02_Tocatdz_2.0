const currentSchemaFixture = `
CREATE TABLE public.users (id serial PRIMARY KEY, email text NOT NULL, note text DEFAULT 'baru');
CREATE TABLE public.legacy (id integer);
CREATE INDEX users_note_idx ON public.users (note);
CREATE VIEW public.emails AS SELECT email FROM public.users;
INSERT INTO public.users (email) VALUES ('a@x.test');
`

const desiredSchemaFixture = `
CREATE TABLE public.users (id serial PRIMARY KEY, email varchar(200) NOT NULL CONSTRAINT users_email_key UNIQUE, note text, created_at timestamptz NOT NULL DEFAULT now());
CREATE TABLE public.orders (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id integer NOT NULL REFERENCES public.users (id),
	total numeric(12, 2) NOT NULL DEFAULT 0 CHECK (total >= 0), "Kode Unik" text, "order" text);
CREATE INDEX orders_user_idx ON public.orders (user_id);
CREATE UNIQUE INDEX users_email_lower_idx ON public.users (lower(email));
CREATE VIEW public.emails AS SELECT id, email FROM public.users;
CREATE SCHEMA "Toko Saya";
CREATE TABLE "Toko Saya".produk (id integer PRIMARY KEY, nama text NOT NULL CHECK (length(nama) > 0));
CREATE TABLE "Toko Saya".stok (produk_id integer REFERENCES "Toko Saya".produk (id), jumlah integer NOT NULL DEFAULT 0);
`

func addManagedTarget(t *testing.T, platform *pgxpool.Pool, box *SecretBox, name, fixture string) security.ID {
	t.Helper()
	dsn := createDatabase(t)
	target, err := pgxpool.New(context.Background(), dsn)
	if err != nil {
		t.Fatal(err)
	}
	defer target.Close()
	exec(t, target, fixture)
	runtimeDSN, err := PrepareManagedTarget(context.Background(), platform, security.NewSecret(dsn), box)
	if err != nil {
		t.Fatal(err)
	}
	id := newID(t)
	sealed, err := box.Seal(id, runtimeDSN)
	if err != nil {
		t.Fatal(err)
	}
	exec(t, platform, "INSERT INTO managed_databases (id, name, dsn_ciphertext) VALUES ($1, $2, $3)", string(id), name, sealed)
	return id
}

func applyCandidate(t *testing.T, targets *Targets, id security.ID, sql security.Secret) {
	t.Helper()
	err := targets.WithDatabaseLock(context.Background(), id, func(ctx context.Context, locked migration.LockedTarget) error {
		tx, err := locked.Begin(ctx)
		if err != nil {
			return err
		}
		if err := tx.Execute(ctx, sql); err != nil {
			_ = tx.Rollback(ctx)
			return err
		}
		return tx.Commit(ctx)
	})
	if err != nil {
		t.Fatalf("candidate SQL failed: %v\n%s", err, sql.Reveal())
	}
}

func TestSchemaDiffCandidateConvergesRealDatabases(t *testing.T) {
	platform := testPlatform(t)
	box, _ := NewSecretBox(testKey(9))
	current := addManagedTarget(t, platform, box, "produksi", currentSchemaFixture)
	desired := addManagedTarget(t, platform, box, "staging", desiredSchemaFixture)
	targets, err := NewTargets(platform, box)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(targets.Close)
	service, err := schemadiff.NewService(schemadiff.Config{Reader: targets, Validator: migration.NewPostgreSQLValidator(), Authorizer: allowAll{}})
	if err != nil {
		t.Fatal(err)
	}
	principal := security.Principal{UserID: newID(t), SessionID: newID(t), AuthVersion: 1, CSRFEpoch: 1}
	ctx := context.Background()
	result, err := service.Compare(ctx, schemadiff.Request{Principal: principal, CurrentID: current, CurrentSchema: "public", DesiredID: desired, DesiredSchema: "public"})
	if err != nil {
		t.Fatal(err)
	}
	sql := result.SQL.Reveal()
	for _, want := range []string{"DROP TABLE public.legacy", "pg_catalog.now()", `"Kode Unik"`, `"order" text`, "GENERATED BY DEFAULT AS IDENTITY", "TYPE character varying(200)", "DROP INDEX public.users_note_idx", "pg_catalog.lower((email)::text)"} {
		if !strings.Contains(sql, want) {
			t.Fatalf("candidate SQL missing %q:\n%s", want, sql)
		}
	}
	if result.Validation != "" || result.Destructive != 1 || len(result.Warnings) == 0 {
		t.Fatalf("unexpected result: validation=%q destructive=%d warnings=%v", result.Validation, result.Destructive, result.Warnings)
	}
	applyCandidate(t, targets, current, result.SQL)
	again, err := service.Compare(ctx, schemadiff.Request{Principal: principal, CurrentID: current, CurrentSchema: "public", DesiredID: desired, DesiredSchema: "public"})
	if err != nil || len(again.Changes) != 0 || !again.SQL.Empty() {
		t.Fatalf("schema did not converge: %+v %v\n%s", again.Changes, err, again.SQL.Reveal())
	}
	var email string
	if err := targets.read(ctx, current, func(tx pgx.Tx) error {
		return tx.QueryRow(ctx, "SELECT email FROM public.users").Scan(&email)
	}); err != nil || email != "a@x.test" {
		t.Fatal("existing rows lost after applying candidate")
	}

	result, err = service.Compare(ctx, schemadiff.Request{Principal: principal, CurrentID: desired, CurrentSchema: "public", DesiredID: desired, DesiredSchema: "Toko Saya"})
	if err != nil || result.Validation != "" {
		t.Fatalf("schema to schema compare failed: %v %q", err, result.Validation)
	}
	if strings.Contains(result.SQL.Reveal(), `"Toko Saya".`) || !strings.Contains(result.SQL.Reveal(), "REFERENCES public.produk(id)") {
		t.Fatalf("references not remapped to current schema:\n%s", result.SQL.Reveal())
	}
	if _, err := targets.Snapshot(ctx, current, "tidak_ada"); !errors.Is(err, security.ErrNotFound) {
		t.Fatal("missing schema not reported as not found")
	}
	if _, err := targets.Snapshot(ctx, current, "pg_catalog"); !errors.Is(err, security.ErrInvalidInput) {
		t.Fatal("system schema readable")
	}
}
